"""
Sparkov simulated credit-card transactions (Kaggle: kartik2112/fraud-detection).

~1.85M transactions, Jan 2019 - Dec 2020, 999 cards with ~1,850 transactions each,
0.52% fraud. Generated by the Sparkov simulator, so patterns are cleaner than real data.

Mapping onto the canonical velocity columns:

    canonical       Sparkov       velocity features it drives
    user_id         cc_num        purchase_cnt/amt_*, time_since_last_txn_uid, median amount
    device_id       merchant      did_uid_* = distinct cards at this merchant in the window
    ip_address      zip           ip_uid_*  = distinct cards in this zip (home zip, so ~1 card
                                              per zip: expected to carry little signal)
    ip_country      category      country_txn_count_* = transactions in this merchant category
    purchase_value  amt
    class           is_fraud
"""
import numpy as np
import pandas as pd

from training.datasets import EXTERNAL_DIR

FILES = ["fraudTrain.csv", "fraudTest.csv"]


def _haversine_km(lat1, lon1, lat2, lon2):
    lat1, lon1, lat2, lon2 = map(np.radians, (lat1, lon1, lat2, lon2))
    a = (np.sin((lat2 - lat1) / 2) ** 2
         + np.cos(lat1) * np.cos(lat2) * np.sin((lon2 - lon1) / 2) ** 2)
    return 6371 * 2 * np.arcsin(np.sqrt(a))


def to_canonical(raw: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return (canonical frame, static features), both sorted by purchase_time."""
    raw = raw.assign(purchase_time=pd.to_datetime(raw["trans_date_trans_time"]))
    raw = raw.sort_values("purchase_time", kind="stable").reset_index(drop=True)

    canonical = pd.DataFrame({
        "purchase_time": raw["purchase_time"],
        "user_id": raw["cc_num"].astype(str),
        "device_id": raw["merchant"].astype(str),
        "ip_address": raw["zip"],
        "ip_country": raw["category"].astype(str),
        "purchase_value": raw["amt"].astype(float),
        "class": raw["is_fraud"].astype(int),
    })
    age_years = (raw["purchase_time"] - pd.to_datetime(raw["dob"])).dt.days / 365.25
    static = pd.DataFrame({
        "amount": raw["amt"].astype(float),
        "category": pd.Categorical(raw["category"]).codes,
        "gender": (raw["gender"] == "F").astype(int),
        "age": age_years.round(1),
        "city_pop": raw["city_pop"],
        "merchant_distance_km": _haversine_km(raw["lat"], raw["long"],
                                              raw["merch_lat"], raw["merch_long"]),
        "hour_of_day": raw["purchase_time"].dt.hour,
        "day_of_week": raw["purchase_time"].dt.dayofweek,
    })
    return canonical, static


def load() -> tuple[pd.DataFrame, pd.DataFrame]:
    folder = EXTERNAL_DIR / "sparkov"
    raw = pd.concat([pd.read_csv(folder / f, index_col=0) for f in FILES], ignore_index=True)
    return to_canonical(raw)
